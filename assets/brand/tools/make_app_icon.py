#!/usr/bin/env python3
"""Generate the black-and-white V app-icon and TV-banner masters.

Owner decision 2026-10-27 (design#21): the app icon is a simple black and
white V. The V is the Bricolage Grotesque ExtraBold "V" outline read from
assets/fonts/remote_bricolage_800.ttf, set at 0.625 x the mark size and
centred on its ink box (the KMP BrandMark and make_remote_branding.py ratio).

Outputs, in assets/brand/app-icon/:
  app-icon-square.svg       72 x 72 full-bleed square: white V on black
  app-icon-square-1024.png  the same square at 1024 px
  app-icon-foreground.svg   108 x 108 adaptive foreground: white V sized for
                            the 72-unit visible area, transparent ground
  app-icon-monochrome.svg   the same V as a single-colour silhouette for
                            themed (monochrome) icons
  tv-banner-320x180.png     xhdpi TV banner: the remote channel-poster lockup
                            in black and white, scaled to 180 px high

Requires Pillow and fontTools (pinned so the PNG bytes reproduce):
  python3 -m venv /tmp/viptv-icons
  /tmp/viptv-icons/bin/pip install pillow==13.0.0 fonttools==4.67.0
  /tmp/viptv-icons/bin/python assets/brand/tools/make_app_icon.py
  /tmp/viptv-icons/bin/python assets/brand/tools/make_app_icon.py --check
"""
import sys
import tempfile
from pathlib import Path

from fontTools.pens.recordingPen import RecordingPen
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

ASSETS = Path(__file__).resolve().parents[2]
FONT = ASSETS / "fonts/remote_bricolage_800.ttf"
OUT = ASSETS / "brand/app-icon"

BLACK = "#000000"   # tokens color.bg-oled
WHITE = "#FFFFFF"   # tokens color.fill.white
GLYPH_RATIO = 0.625  # V font size / mark size
CORNER = 0.28        # banner mark corner radius / mark size
OVERSAMPLE = 8

# Adaptive icons are a 108-unit canvas; launchers mask the centre 72 units.
CANVAS, VISIBLE = 108, 72
WORDMARK = "VIPTV"


def v_outline():
    """The V glyph as closed polygons in font units (y up), plus its ink box."""
    font = TTFont(FONT)
    pen = RecordingPen()
    font.getGlyphSet()[font.getBestCmap()[ord("V")]].draw(pen)
    contours, current = [], []
    for op, args in pen.value:
        if op in ("moveTo", "lineTo"):
            current.append(args[0])
        elif op in ("closePath", "endPath"):
            contours.append(current)
            current = []
        else:  # The Bricolage V is straight-edged; fail loudly if that changes.
            raise SystemExit(f"unexpected curve segment {op} in V glyph")
    points = [p for c in contours for p in c]
    xs, ys = [p[0] for p in points], [p[1] for p in points]
    return contours, (min(xs), min(ys), max(xs), max(ys)), font["head"].unitsPerEm


CONTOURS, (X0, Y0, X1, Y1), UPEM = v_outline()


def place_v(mark, cx, cy):
    """V polygons for a mark of `mark` units centred on (cx, cy), y down."""
    scale = mark * GLYPH_RATIO / UPEM
    mx, my = (X0 + X1) / 2, (Y0 + Y1) / 2
    return [[(cx + (x - mx) * scale, cy - (y - my) * scale) for x, y in c] for c in CONTOURS]


def fmt(n):
    return f"{n:.3f}".rstrip("0").rstrip(".")


def path_data(mark, cx, cy):
    return "".join(
        "M" + "L".join(f"{fmt(x)},{fmt(y)}" for x, y in c) + "Z" for c in place_v(mark, cx, cy)
    )


def svg(size, body):
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
        f'viewBox="0 0 {size} {size}">\n'
        "<!-- Generated by assets/brand/tools/make_app_icon.py; do not edit by hand. -->\n"
        f"{body}</svg>\n"
    )


def square_svg():
    return svg(VISIBLE, f'<rect width="{VISIBLE}" height="{VISIBLE}" fill="{BLACK}"/>\n'
               f'<path fill="{WHITE}" d="{path_data(VISIBLE, VISIBLE / 2, VISIBLE / 2)}"/>\n')


def layer_svg(fill):
    return svg(CANVAS, f'<path fill="{fill}" d="{path_data(VISIBLE, CANVAS / 2, CANVAS / 2)}"/>\n')


def square_png(px):
    canvas = px * OVERSAMPLE
    image = Image.new("RGB", (canvas, canvas), BLACK)
    draw = ImageDraw.Draw(image)
    for polygon in place_v(canvas, canvas / 2, canvas / 2):
        draw.polygon(polygon, fill=WHITE)
    return image.resize((px, px), Image.Resampling.LANCZOS)


def banner():
    """320x180 xhdpi TV banner: make_remote_branding.py's 336x210 channel-poster
    lockup (mark 60, text 72, gap 18) scaled to 180 px high, recoloured: a white
    rounded-square mark holding a black V, then a white wordmark, on black."""
    width, height = 320, 180
    scale = height / 210 * OVERSAMPLE
    mark, text_size, gap = 60 * scale, 72 * scale, 18 * scale
    image = Image.new("RGB", (width * OVERSAMPLE, height * OVERSAMPLE), BLACK)
    draw = ImageDraw.Draw(image)
    font = ImageFont.truetype(str(FONT), round(text_size))
    tracking = -text_size * 0.04
    word = sum(font.getlength(c) for c in WORDMARK) + tracking * (len(WORDMARK) - 1)
    x = (image.width - mark - gap - word) / 2
    cy = image.height / 2
    draw.rounded_rectangle((x, cy - mark / 2, x + mark, cy + mark / 2), radius=mark * CORNER, fill=WHITE)
    for polygon in place_v(mark, x + mark / 2, cy):
        draw.polygon(polygon, fill=BLACK)
    x += mark + gap
    _, top, _, bottom = font.getbbox(WORDMARK)
    y = cy - (top + bottom) / 2
    for char in WORDMARK:
        draw.text((x, y), char, font=font, fill=WHITE)
        x += font.getlength(char) + tracking
    return image.resize((width, height), Image.Resampling.LANCZOS)


def generate(out):
    out.mkdir(parents=True, exist_ok=True)
    (out / "app-icon-square.svg").write_text(square_svg())
    (out / "app-icon-foreground.svg").write_text(layer_svg(WHITE))
    (out / "app-icon-monochrome.svg").write_text(layer_svg(BLACK))
    square_png(1024).save(out / "app-icon-square-1024.png", optimize=True)
    banner().save(out / "tv-banner-320x180.png", optimize=True)
    return sorted(p.name for p in out.iterdir())


def main():
    if sys.argv[1:] == ["--check"]:
        with tempfile.TemporaryDirectory() as tmp:
            names = generate(Path(tmp))
            stale = [
                n for n in names
                if not (OUT / n).is_file() or (Path(tmp) / n).read_bytes() != (OUT / n).read_bytes()
            ]
        if stale:
            raise SystemExit(f"regenerate assets/brand/app-icon: {', '.join(stale)} differ")
        print(f"assets/brand/app-icon up to date ({len(names)} files)")
        return
    for name in generate(OUT):
        print(f"assets/brand/app-icon/{name}")


if __name__ == "__main__":
    main()
